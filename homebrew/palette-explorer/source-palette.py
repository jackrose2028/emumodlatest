# Tiny NES homebrew: "Palette Explorer". Left/Right step through the NES colours, Up/Down jump a brightness row,
# A shows the colour number as a bar pattern... (kept simple: colour only). Public domain (CC0).
code=bytearray(); labels={}; fix=[]
def b(*x): code.extend(x)
def L(n): labels[n]=len(code)
def br(op,n): b(op,0); fix.append((len(code)-1,n,'rel'))
def jmp(n): b(0x4C,0,0); fix.append((len(code)-2,n,'abs'))
ORG=0xC000
# reset
L('reset')
b(0x78,0xD8)                 # SEI CLD
b(0xA2,0x40,0x8E,0x17,0x40)  # LDX #$40 STX $4017
b(0xA2,0xFF,0x9A,0xE8)       # LDX #$FF TXS INX
b(0x8E,0x00,0x20,0x8E,0x01,0x20,0x8E,0x10,0x40) # STX $2000 $2001 $4010
L('vb1'); b(0x2C,0x02,0x20); br(0x10,'vb1')     # BIT $2002 BPL
L('vb2'); b(0x2C,0x02,0x20); br(0x10,'vb2')
b(0xA9,0x21,0x85,0x00)       # LDA #$21 STA $00 (colour)
b(0xA9,0x00,0x85,0x02)       # prev buttons = 0
L('main')
L('wait'); b(0x2C,0x02,0x20); br(0x10,'wait')   # wait for vblank
b(0xA9,0x3F,0x8D,0x06,0x20,0xA9,0x00,0x8D,0x06,0x20)  # $2006 = $3F00
b(0xA5,0x00,0x8D,0x07,0x20)  # LDA $00 STA $2007
b(0xA9,0x00,0x8D,0x06,0x20,0x8D,0x06,0x20)  # reset VRAM address
b(0x8D,0x05,0x20,0x8D,0x05,0x20)            # scroll 0,0
b(0xA9,0x08,0x8D,0x01,0x20)  # show background (blank tiles -> backdrop colour)
# read pad 1 into $01 (bit7=A .. bit0=Right)
b(0xA9,0x01,0x8D,0x16,0x40,0xA9,0x00,0x8D,0x16,0x40)
b(0xA2,0x08)
L('rd'); b(0xAD,0x16,0x40,0x4A,0x26,0x01,0xCA); br(0xD0,'rd')
# new presses in $03 = $01 & ~$02
b(0xA5,0x02,0x49,0xFF,0x25,0x01,0x85,0x03)
b(0xA5,0x01,0x85,0x02)
# Right
b(0xA5,0x03,0x29,0x01); br(0xF0,'noR'); b(0xE6,0x00); L('noR')
# Left
b(0xA5,0x03,0x29,0x02); br(0xF0,'noL'); b(0xC6,0x00); L('noL')
# Down: -$10
b(0xA5,0x03,0x29,0x04); br(0xF0,'noD'); b(0xA5,0x00,0x38,0xE9,0x10,0x85,0x00); L('noD')
# Up: +$10
b(0xA5,0x03,0x29,0x08); br(0xF0,'noU'); b(0xA5,0x00,0x18,0x69,0x10,0x85,0x00); L('noU')
# Start: back to $21 ; mask to 0..$3F
b(0xA5,0x03,0x29,0x10); br(0xF0,'noS'); b(0xA9,0x21,0x85,0x00); L('noS')
b(0xA5,0x00,0x29,0x3F,0x85,0x00)
jmp('main')
L('nmi'); b(0x40)            # RTI
for pos,n,kind in fix:
    t=labels[n]
    if kind=='rel':
        off=t-(pos+1); assert -128<=off<=127,(n,off); code[pos]=off&0xFF
    else:
        a=ORG+t; code[pos]=a&0xFF; code[pos+1]=a>>8
prg=bytearray([0xFF]*0x4000); prg[0:len(code)]=code
nmi=ORG+labels['nmi']; rst=ORG+labels['reset']
prg[0x3FFA:0x4000]=bytes([nmi&0xFF,nmi>>8,rst&0xFF,rst>>8,nmi&0xFF,nmi>>8])
hdr=bytes([0x4E,0x45,0x53,0x1A,1,1,0,0])+bytes(8)
open('palette-explorer.nes','wb').write(hdr+prg+bytes(0x2000))
print(len(code),'bytes of code')
